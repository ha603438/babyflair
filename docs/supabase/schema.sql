-- BabyFlair : schéma Supabase (à exécuter une fois dans l'éditeur SQL du projet).
-- Deux tables de données, une table de configuration privée et une règle d'accès par « code du bureau » :
-- l'app envoie l'en-tête HTTP x-office-code, la base ne répond que s'il correspond au code stocké ici.

create table if not exists public.players (
  id uuid primary key,
  name text not null check (char_length(name) between 1 and 24),
  is_guest boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.matches (
  id uuid primary key,
  seq bigint generated by default as identity unique,
  played_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  target smallint not null check (target in (5, 10)),
  team_a uuid[] not null check (cardinality(team_a) between 1 and 2),
  team_b uuid[] not null check (cardinality(team_b) = cardinality(team_a)),
  score_a smallint not null check (score_a between 0 and 10),
  score_b smallint not null check (score_b between 0 and 10),
  check ((score_a = target) <> (score_b = target))
);

-- Configuration privée : aucune règle d'accès, donc invisible depuis l'API. Le code est lu par office_ok().
create table if not exists public.app_config (
  key text primary key,
  value text not null
);

-- Remplace OFFICE_CODE par la phrase secrète partagée aux collègues (à saisir une fois par téléphone).
insert into public.app_config (key, value) values ('office_code', 'OFFICE_CODE')
  on conflict (key) do update set value = excluded.value;

create or replace function public.office_ok() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(current_setting('request.headers', true)::json ->> 'x-office-code', '')
       = (select value from public.app_config where key = 'office_code');
$$;

-- L'app vérifie le code saisi en appelant cette fonction (POST /rest/v1/rpc/office_ok) : elle doit être exécutable
-- par le rôle anonyme. Elle ne révèle rien d'autre que vrai / faux.
grant execute on function public.office_ok() to anon, authenticated;

-- Après un import (INSERT avec un seq explicite), la séquence d'identité doit repartir après le plus grand seq,
-- sinon le prochain match sans seq entrerait en conflit.
create or replace function public.matches_bump_seq() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  perform setval(pg_get_serial_sequence('public.matches', 'seq'), (select max(seq) from public.matches), true);
  return null;
end;
$$;

drop trigger if exists matches_bump_seq on public.matches;
create trigger matches_bump_seq after insert on public.matches
  for each statement execute function public.matches_bump_seq();

alter table public.players enable row level security;
alter table public.matches enable row level security;
alter table public.app_config enable row level security;

drop policy if exists office_players on public.players;
create policy office_players on public.players
  for all to anon, authenticated using (public.office_ok()) with check (public.office_ok());

drop policy if exists office_matches on public.matches;
create policy office_matches on public.matches
  for all to anon, authenticated using (public.office_ok()) with check (public.office_ok());

-- Mises à jour en direct (optionnel) : permet à l'app d'écouter les changements au lieu d'interroger régulièrement.
alter publication supabase_realtime add table public.players, public.matches;
